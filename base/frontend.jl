# The runtime's frontend library (libjulia-frontend), which parses and lowers
# code until this julia's own JuliaSyntax and JuliaLowering take over, i.e.
# while bootstrapping: see JuliaSyntax.enable_in_core! and
# JuliaLowering.activate!.

# Parse with the frontend library. `offset` is 0-based offset into the byte
# buffer or string. The library's interface has no edition parameter: it
# parses the edition of Expr syntax (FLISP_EDITION).
function frontend_parse(text::Union{Core.SimpleVector,String},
                        filename::String, lineno, offset, options, edition)
    if edition != FLISP_EDITION
        error("Edition $edition not supported by the frontend library (expected $FLISP_EDITION)")
    end
    if text isa Core.SimpleVector
        # Will be generated by C entry points jl_parse etc
        text, text_len = text
    else
        text_len = sizeof(text)
    end
    ccall(:jl_frontend_parse, Any, (Ptr{UInt8}, Csize_t, Any, Csize_t, Csize_t, Any),
          text, text_len, filename, lineno, offset, options)
end

function frontend_parse(text::AbstractString, filename::AbstractString, lineno,
                        offset, options, edition)
    frontend_parse(String(text), String(filename), lineno, offset, options, edition)
end

function frontend_lower(mod::Module, @nospecialize(ex), world::UInt, warn::Bool,
                        loc::LineNumberNode)
    ccall(:jl_frontend_lower, Any, (Any, Any, Csize_t, Cint, Any),
          mod, ex, world, warn, loc)
end

# The frontend library's lowering treats all syntax as FLISP_EDITION, so
# choosing it also opts out of editions > FLISP_EDITION.
function frontend_toplevel_eval(mod::Module, @nospecialize(x))
    ex = if x isa Syntax
        Expr(:toplevel, first_linenode(x), syntax_to_expr(x))
    else
        x
    end
    ccall(:jl_toplevel_eval, Any, (Any, Any), mod, ex)
end
