function pop!(h::Dict)
    isempty(h) && throw(ArgumentError("dict must be non-empty"))
    dense_ind = h.count
    p = @inbounds h.entries[dense_ind]
    sparse_ind = _slot_index(h, dense_ind, @inbounds _gethash(h, dense_ind))
    _delete!(h, sparse_ind, dense_ind)
    return p
end

function _delete!(h::Dict, sparse_ind, dense_ind)
    return h.wide ? _delete_wide!(h, sparse_ind, dense_ind) : _delete!(h, sparse_ind, dense_ind, false)
end
@noinline _delete_wide!(h::Dict, sparse_ind, dense_ind) = _delete!(h, sparse_ind, dense_ind, true)
@inline function _delete!(h::Dict{K}, sparse_ind, dense_ind, wide::Bool) where K
    @inbounds begin
    (;slots, hashes, entries) = h
    sz = _nslots(slots, wide)
    if h.count != dense_ind
        # swap last entry with deleted entry to avoid tombstone
        last_hsh = _gethash(h, h.count)
        last_sparse = _slot_index(h, h.count, last_hsh, wide)
        _setslot!(slots, last_sparse, wide, slot_encode(last_hsh, dense_ind, sz))
        _store_hashes(K) && (hashes[dense_ind] = last_hsh)
        entries[dense_ind] = entries[h.count]
    end
    unsetindex!(entries, h.count)
    mask = sz - 1
    hole = sparse_ind
    _setslot!(slots, hole, wide, UInt64(0))
    @assume_effects :terminates_locally for _ in 1:sz
        sparse_ind = (sparse_ind & mask) + 1
        slot = _getslot(slots, sparse_ind, wide)
        iszero(slot) && break
        home = (_gethash(h, (slot & mask) % Int) & mask) % Int + 1
        # move back unless home is in (hole, sparse_ind], comparing cyclic distances behind sparse_ind.
        # Branchless: the hole always holds 0, so both stores are unconditional selects.
        mv = ((sparse_ind - home) & mask) >= ((sparse_ind - hole) & mask)
        _setslot!(slots, hole, wide, ifelse(mv, slot, UInt64(0)))
        _setslot!(slots, sparse_ind, wide, ifelse(mv, UInt64(0), slot))
        hole = ifelse(mv, sparse_ind, hole)
    end
    h.count -= 1
    h.age += 1
    return h
    end
end

"""
    delete!(collection, key)

Delete the mapping for the given key in a collection, if any, and return the collection.

# Examples
```jldoctest; filter = r"^\\s+\\S+\\s+=>\\s+\\d\$"m
julia> d = Dict("a"=>1, "b"=>2)
Dict{String, Int64} with 2 entries:
  "b" => 2
  "a" => 1

julia> delete!(d, "b")
Dict{String, Int64} with 1 entry:
  "a" => 1

julia> delete!(d, "b") # d is left unchanged
Dict{String, Int64} with 1 entry:
  "a" => 1
```
"""
delete!(collection, key)

function delete!(h::Dict, key)
    sparse_ind, dense_ind, found = _probe_lookup(h, key)
    if found
        _delete!(h, sparse_ind, dense_ind)
    end
    return h
end

function iterate(h::Dict, i::Int = h.count)
    1 <= i <= h.count || return nothing
    return (@inbounds h.entries[i], i-1)
end

isempty(h::Dict) = (h.count == 0)
length(h::Dict) = h.count

@propagate_inbounds Iterators.only(t::Dict) = Iterators._only(t, first)

function iterate(v::T, i::Int = v.dict.count) where T <: Union{KeySet{<:Any, <:Dict}, ValueIterator{<:Dict}}
    1 <= i <= v.dict.count || return nothing
    field = T <: KeySet ? :first : :second
    @inbounds (getfield(v.dict.entries[i], field), i-1)
end

function filter!(pred, h::Dict)
    @inbounds for dense_ind=h.count:-1:1
        if !pred(h.entries[dense_ind])
            sparse_ind = _slot_index(h, dense_ind, _gethash(h, dense_ind))
            _delete!(h, sparse_ind, dense_ind)
        end
    end
    return h
end

function reduce(::typeof(merge), items::Vector{<:Dict})
    K = mapreduce(keytype, promote_type, items)
    V = mapreduce(valtype, promote_type, items)
    return reduce(merge!, items; init=Dict{K,V}())
end

function map!(f, iter::ValueIterator{<:Dict{K, V}}) where {K, V}
    dict = iter.dict
    entries = dict.entries
    @inbounds for i = 1:dict.count
        key, val = entries[i]
        entries[i] = Pair{K, V}(key, f(val))
    end
    return iter
end

function mergewith!(combine, d1::Dict{K, V}, d2::AbstractDict) where {K, V}
    haslength(d2) && sizehint!(d1, length(d1) + length(d2), shrink=false)
    for (k, v) in d2
        hsh = hash(k)::UInt
        sparse_ind, dense_ind, found = _probe(d1, k, hsh)
        if found
            key, val = @inbounds d1.entries[dense_ind]
            @inbounds d1.entries[dense_ind] = Pair{K, V}(key, combine(val, v))
        else
            if !(k isa K)
                k1 = convert(K, k)::K
                if !isequal(k, k1)
                    throw(KeyTypeError(K, k))
                end
                k = k1
            end
            if !isa(v, V)
                v = convert(V, v)::V
            end
            _setindex!(d1, hsh, Pair{K, V}(k, v), sparse_ind, dense_ind)
        end
    end
    return d1
end

struct ImmutableDict{K,V} <: AbstractDict{K,V}
    parent::ImmutableDict{K,V}
    key::K
    value::V
    ImmutableDict{K,V}() where {K,V} = new() # represents an empty dictionary
    ImmutableDict{K,V}(key, value) where {K,V} = (empty = new(); new(empty, key, value))
    ImmutableDict{K,V}(parent::ImmutableDict, key, value) where {K,V} = new(parent, key, value)
end

"""
    ImmutableDict

`ImmutableDict` is a dictionary implemented as an immutable linked list,
which is optimal for small dictionaries that are constructed over many individual insertions.
Note that it is not possible to remove a value, but a new value with the same
key may be added. Calling `getindex` will return the most recent value for a
particular key, but iterating will show all `key => value` pairs.

- Use `(key => value) in dict` to see if this particular combination is in the
  properties set.
- Use `get(dict, key, default)` to retrieve the most recent value for a particular key.
- Iterate over `dict` to see all `key => value` pairs, including duplicate keys.
  Iteration is in reverse order, from most recently added to least recently
  added.

    ImmutableDict(KV::Pair...)

Create a new `ImmutableDict` containing the provided `key => value` pairs.

    ImmutableDict(d::ImmutableDict, KV::Pair...)

Return a new `ImmutableDict` containing all of the `key => value` pairs of `d`
as well as new entries for the provided `key => value` pairs.
"""
ImmutableDict
ImmutableDict(KV::Pair{K,V}) where {K,V} = ImmutableDict{K,V}(KV[1], KV[2])
ImmutableDict(t::ImmutableDict{K,V}, KV::Pair) where {K,V} = ImmutableDict{K,V}(t, KV[1], KV[2])
ImmutableDict(t::ImmutableDict{K,V}, KV::Pair, rest::Pair...) where {K,V} =
    ImmutableDict(ImmutableDict(t, KV), rest...)
ImmutableDict(KV::Pair, rest::Pair...) = ImmutableDict(ImmutableDict(KV), rest...)

function in(key_value::Pair, dict::ImmutableDict, valcmp=(==))
    key, value = key_value
    while isdefined(dict, :parent)
        if isequal(dict.key, key)
            valcmp(value, dict.value) && return true
        end
        dict = dict.parent
    end
    return false
end

function haskey(dict::ImmutableDict, key)
    while isdefined(dict, :parent)
        isequal(dict.key, key) && return true
        dict = dict.parent
    end
    return false
end

function getindex(dict::ImmutableDict, key)
    while isdefined(dict, :parent)
        isequal(dict.key, key) && return dict.value
        dict = dict.parent
    end
    throw(KeyError(key))
end
function get(dict::ImmutableDict, key, default)
    while isdefined(dict, :parent)
        isequal(dict.key, key) && return dict.value
        dict = dict.parent
    end
    return default
end

function get(default::Callable, dict::ImmutableDict, key)
    while isdefined(dict, :parent)
        isequal(dict.key, key) && return dict.value
        dict = dict.parent
    end
    return default()
end

# this actually defines reverse iteration (e.g. it should not be used for merge/copy/filter type operations)
function iterate(d::ImmutableDict{K,V}, t=d) where {K, V}
    !isdefined(t, :parent) && return nothing
    (Pair{K,V}(t.key, t.value), t.parent)
end
length(t::ImmutableDict) = count(Returns(true), t)
isempty(t::ImmutableDict) = !isdefined(t, :parent)
empty(::ImmutableDict, ::Type{K}, ::Type{V}) where {K, V} = ImmutableDict{K,V}()

"""
    setindex(d::ImmutableDict, value, key)

Creates a new `ImmutableDict` similar to `d` with the most recent value of the
key `key` set to `value`.

Any existing values with the same key remain in `d`, but they are shadowed by
this new value when using [`getindex`](@ref). The existing values are still
present when iterating over `d`.

# Examples
```jldoctest
julia> Base.setindex(Base.ImmutableDict(:a => 1), 2, :a) == Base.ImmutableDict(:a => 1, :a => 2)
true
julia> Base.setindex(Base.ImmutableDict(:a => 1), 2, :b) == Base.ImmutableDict(:a => 1, :b => 2)
true
```
"""
function setindex(d::ImmutableDict, value, key)
    ImmutableDict(d, key => value)
end

